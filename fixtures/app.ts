/**
 * Applications for the suites: the same `AxiSparkContext` that `AxiSparkFactory.create()` builds, without banner and
 * with the logs discarded, so the measurement does not include writing to the console.
 */
import { AxiSparkContext, AxiSparkCore, type AxiSparkConfig, type PluginOptions, type PluginType } from '@axisparkjs/core';
import { ClassRegistry } from '@axisparkjs/di';
import { LogLevel, NullTransport, SimpleFormatter } from '@axisparkjs/logger';

export function nullTransports() {
    return [new NullTransport({ minLevel: LogLevel.Error, formatter: new SimpleFormatter() })];
}

export interface AppOptions extends AxiSparkConfig {
    plugins?: (PluginType | [PluginType, PluginOptions])[];
    /** `null` skips the file system scan (default), `file-system` scans `basePath`. */
    scan?: 'null' | 'file-system';
}

/**
 * Creates an application. `run()` returns once the plugins have started (`wait: false`), like the test factory does,
 * instead of waiting for a termination signal.
 */
export function createApp(options: AppOptions = {}): AxiSparkCore {
    return createAppWithContext(options).app;
}

/** Like `createApp()`, also returns the context of the application (its container, logger and plugins). */
export function createAppWithContext({ plugins = [], scan = 'null', ...config }: AppOptions = {}): { app: AxiSparkCore; context: AxiSparkContext } {
    const context = new AxiSparkContext(
        { name: 'Bench', banner: false, environment: 'production', logTransports: nullTransports(), ...config },
        { scanner: scan, wait: false }
    );
    const app = new AxiSparkCore(context);
    for (const plugin of plugins) {
        if (Array.isArray(plugin)) app.use(plugin[0], plugin[1]);
        else app.use(plugin);
    }
    return { app, context };
}

/**
 * Classes generated by a fixture are registered in the global `ClassRegistry` by their decorators, and every
 * application binds all of them. A task that compares sizes (10, 100, 500 plugins) keeps only its own classes
 * registered with `only()`, so the other sizes do not change its measurement.
 */
export class ClassGroups {
    private readonly groups = new Map<string, Function[]>();

    add(name: string, classes: Function[]): void {
        this.groups.set(name, classes);
    }

    only(name: string): void {
        for (const [group, classes] of this.groups) {
            for (const cls of classes) {
                if (group === name) ClassRegistry.register(cls as never);
                else ClassRegistry.remove(cls as never);
            }
        }
    }
}
